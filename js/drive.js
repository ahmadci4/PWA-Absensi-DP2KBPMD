// Fungsi pintar untuk mencari link berdasarkan nama
export function getDriveLinkByName(name) {
    // Cari nama yang paling cocok (mengabaikan huruf besar/kecil atau salah spasi sedikit)
    const normalizedTargetName = name.trim().toUpperCase();
    
    for (const [dbName, link] of Object.entries(driveLinks)) {
        // Jika nama di aplikasi mengandung kata kunci dari nama di PDF atau sebaliknya
        if (dbName.toUpperCase().includes(normalizedTargetName) || normalizedTargetName.includes(dbName.toUpperCase().split(',')[0])) {
            return link;
        }
    }
    
    // Jika tidak ditemukan, kembalikan null
    return null;
}